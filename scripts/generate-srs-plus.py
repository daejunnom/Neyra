#!/usr/bin/env python3
"""Generate Rust kicks from Clearra's reviewed official-source SRS+ fixture.

No network access or JavaScript execution is needed. The fixture is extracted
by Clearra's scripts/tools/extract-tetrio-srs-plus.py from a separately pinned
TETR.IO bundle. Keep this generator, its fixture and its Rust output together.
Use --check in CI to detect stale or manually edited generated data.
"""

import argparse
import difflib
import hashlib
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "crates/neyra-core/tests/fixtures/tetrio_srs_plus_standard_tetromino_kicks.json"
OUTPUT = ROOT / "crates/neyra-core/src/srs_plus.rs"
PIECES = ("I", "J", "L", "O", "S", "T", "Z")
SCHEMA = "clearra.tetrio-srs-plus-standard-tetromino-kicks.v1"


def read_fixture(path):
    fixture = json.loads(path.read_text(encoding="utf-8"))
    if fixture.get("schema") != SCHEMA:
        raise ValueError("Unsupported canonical SRS+ fixture schema")
    if fixture.get("authority") != "https://tetr.io/js/tetrio.js":
        raise ValueError("Unexpected SRS+ source authority")
    if fixture.get("clearra_axis") != {"x": "right-positive", "y": "up-positive"}:
        raise ValueError("Rust kicks require x-right, y-up coordinates")
    if not fixture.get("implicit_origin_attempt") or not fixture.get("first_success_order_preserved"):
        raise ValueError("The fixture must include the ordered origin attempt")
    if not re.fullmatch(r"[0-9a-f]{64}", fixture.get("source_sha256", "")):
        raise ValueError("The fixture must pin its source SHA-256")

    transitions = fixture["transitions_y_up"]
    expected = {f"{piece}:{start}{end}" for piece in PIECES for start in range(4)
                for end in range(4) if start != end}
    if set(transitions) != expected:
        raise ValueError("The fixture must contain all 84 standard tetromino transitions")
    for key, offsets in transitions.items():
        if not offsets or offsets[0] != [0, 0]:
            raise ValueError(f"{key}: origin must be attempted first")
        if any(not isinstance(pair, list) or len(pair) != 2
               or any(type(value) is not int or not -128 <= value <= 127 for value in pair)
               for pair in offsets):
            raise ValueError(f"{key}: expected ordered pairs of i8 offsets")
    encoded = json.dumps(transitions, sort_keys=True, separators=(",", ":")).encode()
    if hashlib.sha256(encoded).hexdigest() != fixture.get("transitions_sha256"):
        raise ValueError("Canonical transition checksum mismatch")
    return fixture


def render(fixture):
    # Intern equal sequences and equal piece tables; no family relationships
    # or numeric offsets are hand-maintained in this generator.
    sequences = [()]
    tables = {}
    for piece in PIECES:
        table = []
        for start in range(4):
            row = []
            for end in range(4):
                offsets = () if start == end else tuple(
                    tuple(pair) for pair in fixture["transitions_y_up"][f"{piece}:{start}{end}"]
                )
                if offsets not in sequences:
                    sequences.append(offsets)
                row.append(sequences.index(offsets))
            table.append(tuple(row))
        tables.setdefault(tuple(table), []).append(piece)

    lines = [
        "//! Generated by `python3 scripts/generate-srs-plus.py`; do not edit.",
        "//! Canonical fixture: tests/fixtures/tetrio_srs_plus_standard_tetromino_kicks.json.",
        "//! Extracted by Clearra from https://tetr.io/js/tetrio.js.",
        f"//! Source SHA-256: {fixture['source_sha256']}",
        f"//! Transition SHA-256: {fixture['transitions_sha256']}",
        "//! Ordered attempts include origin and use x-right, y-up coordinates.",
        "",
        "use crate::physics::Piece;",
        "",
    ]
    for index, offsets in enumerate(sequences):
        pairs = ", ".join(f"({x}, {y})" for x, y in offsets)
        lines.append(f"const KICKS_{index}: &[(i8, i8)] = &[{pairs}];")
    for index, table in enumerate(tables):
        lines += ["", f"const TABLE_{index}: [[&[(i8, i8)]; 4]; 4] = ["]
        for row in table:
            lines.append("    [" + ", ".join(f"KICKS_{sequence}" for sequence in row) + "],")
        lines.append("];")
    lines += [
        "",
        "pub(crate) fn kicks(piece: Piece, from: u8, to: u8) -> &'static [(i8, i8)] {",
        "    if from >= 4 || to >= 4 {",
        "        return &[];",
        "    }",
        "    let table = match piece {",
    ]
    for index, pieces in enumerate(tables.values()):
        pattern = " | ".join(f"Piece::{piece}" for piece in pieces)
        lines.append(f"        {pattern} => &TABLE_{index},")
    lines += ["    };", "    table[from as usize][to as usize]", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture", type=Path, default=FIXTURE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        expected = render(read_fixture(args.fixture))
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.error(str(error))
    if args.check:
        actual = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if actual != expected:
            print("".join(difflib.unified_diff(
                actual.splitlines(keepends=True), expected.splitlines(keepends=True),
                fromfile=str(args.output), tofile="canonical SRS+ output",
            )), end="")
            raise SystemExit("SRS+ output is stale; run python3 scripts/generate-srs-plus.py")
        print("SRS+ Rust module matches the canonical fixture (84 ordered transitions).")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(expected, encoding="utf-8")
        print(f"Generated {args.output.relative_to(ROOT) if args.output.is_relative_to(ROOT) else args.output}")


if __name__ == "__main__":
    main()
